export type I18nKey = keyof typeof vi

const dictionaries: Record<Locale, Record<I18nKey, string>> = { vi, en }

export function translate(
  locale: Locale,
  key: I18nKey,
  params?: Record<string, string | number>
): string {
  let value = dictionaries[locale][key] ?? dictionaries.vi[key] ?? key
  if (params) {
    for (const [name, replacement] of Object.entries(params)) {
      value = value.split(`{${name}}`).join(String(replacement))
    }
  }
  return value
}

export function errorText(locale: Locale, code: ErrorCode, detail?: string): string {
  const base = translate(locale, `err.${code}` as I18nKey)
  if (!detail) return base
  const cleaned = detail.replace(/[\u0000-\u001f\u007f]+/g, ' ').trim().slice(0, 160)
  return cleaned ? `${base} (${cleaned})` : base
}
